
namespace Lumel.Windows
{
    /// <summary>A button a message box can show, identified by the role it plays.</summary>
    public enum MessageBoxAnswer
    {
        /// <summary>The answer that confirms what was asked.</summary>
        Yes,

        /// <summary>The answer that declines what was asked.</summary>
        No,

        /// <summary>Dismisses the question without answering it.</summary>
        Cancel
    }
}
