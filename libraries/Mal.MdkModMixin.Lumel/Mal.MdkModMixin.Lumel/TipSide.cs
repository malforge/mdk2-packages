namespace Lumel
{
    /// <summary>The side of the explained element on which a codex tip is placed, edge to edge with it.</summary>
    public enum TipSide
    {
        /// <summary>To the right of the element, with their tops aligned.</summary>
        Right,

        /// <summary>To the left of the element, with their tops aligned.</summary>
        Left,

        /// <summary>Above the element, with their left edges aligned.</summary>
        Above,

        /// <summary>Below the element, with their left edges aligned.</summary>
        Below
    }
}
